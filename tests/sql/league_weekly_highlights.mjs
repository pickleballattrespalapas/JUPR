import assert from 'node:assert/strict';
import fs from 'node:fs';
const { PGlite } = await import('@electric-sql/pglite');
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
 create table leagues_metadata(club_id text, league_name text, unique(club_id,league_name));
 create table admin_activity_log(id bigint generated by default as identity primary key, club_id text, actor_email text,
 actor_role text, action_type text, entity_type text, entity_id text, before_json jsonb, after_json jsonb, source_page text, flagged_for_review boolean);
 grant all on leagues_metadata, admin_activity_log to service_role;
 grant usage on all sequences in schema public to service_role;
 insert into leagues_metadata values ('club','Open'),('other','Open'),('club','Different');`);
await db.exec(fs.readFileSync(new URL('../../supabase/migrations/20261026043617_league_weekly_highlights.sql', import.meta.url), 'utf8'));
await db.exec('set role service_role');
const save = (ids=['unbeaten:1'], revision=0, week=2, club='club', league='Open', mode='curated', role='administrator') =>
  db.query('select save_league_weekly_highlights($1,$2,$3,$4,$5,$6,$7,$8) result', [club,league,week,mode,ids,revision,'admin@example.com',role]);
assert.equal((await save()).rows[0].result.revision, 1);
assert.equal((await save()).rows[0].result.revision, 1, 'lost-response retry is idempotent');
assert.equal((await db.query('select count(*) n from admin_activity_log')).rows[0].n, 1);
await assert.rejects(() => save(['wins:2']), /reload/);
await save(['wins:2','unbeaten:1'], 1);
assert.deepEqual((await db.query('select selected_ids from league_weekly_highlights')).rows[0].selected_ids, ['wins:2','unbeaten:1']);
await save([], 2);
assert.equal((await db.query('select mode from league_weekly_highlights')).rows[0].mode, 'curated', 'intentional empty persists');
await save(['games:1'],0,1);
await save(['games:2'],0,2,'other');
await save(['games:3'],0,2,'club','Different');
assert.equal((await db.query('select count(*) n from league_weekly_highlights')).rows[0].n, 4);
await assert.rejects(() => save(['games:1'],0,2,'missing'), /foreign key/);
await assert.rejects(() => save([],3,2,'club','Open','curated','operator'), /Only club administrators/);
await assert.rejects(() => save(['x','x'],3), /distinct/);
await assert.rejects(() => save(['x'],3,2,'club','Open','automatic'), /distinct/);
await assert.rejects(() => save([1],3), /distinct/);
await save([],3,2,'club','Open','automatic');
const before = (await db.query('select count(*) n from admin_activity_log')).rows[0].n;
await db.exec('reset role; revoke insert on admin_activity_log from service_role; set role service_role');
await assert.rejects(() => save(['wins:1'],4), /permission denied/);
assert.equal((await db.query("select revision from league_weekly_highlights where club_id='club' and league_name='Open' and week_num=2")).rows[0].revision, 4, 'audit failure rolls back choice');
assert.equal((await db.query('select count(*) n from admin_activity_log')).rows[0].n, before);
await db.exec('reset role');
const permissions = (await db.query(`select
 has_function_privilege('anon','save_league_weekly_highlights(text,text,integer,text,jsonb,bigint,text,text)','execute') anon_call,
 has_function_privilege('authenticated','save_league_weekly_highlights(text,text,integer,text,jsonb,bigint,text,text)','execute') auth_call,
 has_table_privilege('authenticated','league_weekly_highlights','select') auth_read,
 (select relrowsecurity from pg_class where relname='league_weekly_highlights') rls`)).rows[0];
assert.deepEqual(permissions, {anon_call:false, auth_call:false, auth_read:false, rls:true});
await db.exec('set role anon');
await assert.rejects(() => save(), /permission denied/);
await assert.rejects(() => db.query('select * from league_weekly_highlights'), /permission denied/);
await db.close();
console.log('Weekly highlights SQL: ordered selection, empty selection, isolation, revision conflicts, safe retries, atomic audit, RLS and grants passed.');
